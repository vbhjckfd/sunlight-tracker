// Stamps the current git commit into extension/src/commit.generated.ts so the
// content script can log which commit it was built from — the only reliable
// way to tell a stale unpacked-extension load apart from a real code bug when
// debugging against a live lun.ua page.
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

function run(cmd) {
  return execSync(cmd, { encoding: "utf8" }).trim();
}

let hash;
try {
  hash = run("git rev-parse --short HEAD");
} catch {
  hash = "unknown";
}

let dirty = false;
try {
  run("git diff --quiet");
} catch {
  dirty = true;
}

const commit = dirty ? `${hash}-dirty` : hash;
const outPath = fileURLToPath(new URL("../extension/src/commit.generated.ts", import.meta.url));
writeFileSync(outPath, `// Generated by scripts/write-extension-commit.mjs — do not edit, do not commit.\nexport const SLT_COMMIT = ${JSON.stringify(commit)};\n`);
console.log(`extension/src/commit.generated.ts → ${commit}`);
